// The renderer hyphenates by default, which breaks short labels mid-word ("Medi-um"). Words in this
// report are short enough to wrap whole.
Font.registerHyphenationCallback((word) => [word]);

/**
 * The management report as an A4 document, drawn from the same four answers the page shows, so
 * the file and the screen cannot disagree. Imported only when someone downloads, which keeps the
 * PDF renderer out of the app's main bundle.
 *
 * Built-in Helvetica throughout: the app's display face ships as OTF, which the renderer handles
 * unreliably, and a report that fails to download is worse than one in a plainer face.
 */
export function ReportPdfDocument({ meta, overview, propertyTypes, owners, training, colours }) {
  const s = styles(colours);
  const n = (v) => Number(v ?? 0).toLocaleString('en-NZ');

  return (
    <Document title={`Management report – ${meta.firmName}`} author="AMLDOCK" creator="AMLDOCK">
      <Page size="A4" style={s.page}>
        <View fixed style={s.footer}>
          <Text>{meta.firmName} management report, {meta.windowShort}</Text>
          <Text render={({ pageNumber, totalPages }) => `Page ${pageNumber} of ${totalPages}`} />
        </View>

        {/* ── header ── */}
        <Text style={s.title}>Management report</Text>
        <Text style={s.firm}>{meta.firmName}</Text>
        <Text style={s.scope}>{meta.branchName}. {meta.windowSentence}</Text>
        <Text style={s.generated}>Generated by {meta.generatedBy} on {meta.generatedAt}.</Text>

        {/* ── figures ── */}
        <View style={s.figures}>
          <View style={[s.figure, s.figureLead]}>
            <Text style={s.figureLabel}>Deals created</Text>
            <Text style={[s.figureValue, s.figureValueLead]}>{n(overview.created)}</Text>
          </View>
          {[
            ['Open', overview.open, colours.status.REVIEW],
            ['Verified', overview.verified, colours.status.VERIFIED],
            ['Sold', overview.sold, colours.status.CLOSED],
            ['Closed, not sold', overview.closedNotSold, colours.status.NEW],
          ].map(([label, value, swatch]) => (
            <View key={label} style={s.figure}>
              <View style={s.swatchRow}>
                <View style={[s.swatch, { backgroundColor: swatch }]} />
                <Text style={s.figureLabel}>{label}</Text>
              </View>
              <Text style={s.figureValue}>{n(value)}</Text>
            </View>
          ))}
        </View>

        {/* ── charts ── */}
        <View style={s.donuts} wrap={false}>
          <View style={s.donutCell}>
            <Text style={s.h2}>Deals listed</Text>
            <Bars s={s} items={meta.listedBars} />
            {meta.listedBars.length === 1 && (
              <Text style={s.note}>An all-time window has no year before it to compare with.</Text>
            )}
          </View>
          <View style={s.donutCell}>
            <Text style={s.h2}>Appraised and closing value ({meta.currency})</Text>
            <Bars s={s} format={(v) => formatMoney(v, meta.country)} items={[
              { label: 'Appraised value', value: Number(overview.appraisedValue ?? 0), colour: colours.status.REVIEW },
              { label: 'Closing value', value: Number(overview.closingValue ?? 0), colour: colours.status.CLOSED },
            ]} />
          </View>
        </View>

        <View style={s.donuts} wrap={false}>
          <View style={s.donutCell}>
            <Text style={s.h2}>Assurance, signed-off deals</Text>
            <Donut s={s} unit="deals" slices={ASSURANCE_KEYS.map((k) => ({
              key: k, label: assuranceLabel(k), value: overview.byAssurance?.[k] ?? 0, colour: colours.assurance[k],
            }))} track={colours.track} />
          </View>
          <View style={s.donutCell} />
        </View>

        {/* ── property types ── */}
        <Text style={s.h2} minPresenceAhead={80}>Deals by property type</Text>
        <PropertyTable s={s} data={propertyTypes} country={meta.country} windowShort={meta.windowShort} n={n} />

        {/* ── owners ── */}
        <Text style={s.h2} minPresenceAhead={80}>Owners by type</Text>
        <OwnerTable s={s} data={owners} n={n} />

        {/* ── training ── */}
        <Text style={s.h2} minPresenceAhead={80}>Staff training</Text>
        <TrainingTable s={s} data={training} n={n} />
      </Page>
    </Document>
  );
}

/* ---------- charts ---------- */

/** Bars side by side, each figure above its bar and its name below. items: [{ label, value, colour }] */
function Bars({ s, items, format = (v) => v.toLocaleString('en-NZ') }) {
  const max = Math.max(1, ...items.map((x) => x.value));
  return (
    <View>
      <View style={s.barArea}>
        {items.map((x) => (
          <View key={x.label} style={s.barCol}>
            <Text style={s.barValue}>{format(x.value)}</Text>
            <View style={[s.bar, {
              height: x.value ? Math.max(2, (x.value / max) * 96) : 0,
              backgroundColor: x.colour,
            }]} />
          </View>
        ))}
      </View>
      <View style={s.barLabels}>
        {items.map((x) => <Text key={x.label} style={s.barLabel}>{x.label}</Text>)}
      </View>
    </View>
  );
}

const W = 150;
const R_OUT = 70;
const R_IN = 47;

/** Annular sector along the upper half-circle, from angle a0 down to a1 (radians, PI = left). */
function sector(a0, a1) {
  const cx = W / 2;
  const cy = R_OUT;
  const pt = (r, a) => `${(cx + r * Math.cos(a)).toFixed(2)} ${(cy - r * Math.sin(a)).toFixed(2)}`;
  return `M ${pt(R_OUT, a0)} A ${R_OUT} ${R_OUT} 0 0 1 ${pt(R_OUT, a1)}`
    + ` L ${pt(R_IN, a1)} A ${R_IN} ${R_IN} 0 0 0 ${pt(R_IN, a0)} Z`;
}

function Donut({ s, slices, unit, track }) {
  const total = slices.reduce((t, x) => t + x.value, 0);
  let angle = Math.PI;
  const arcs = total === 0
    ? [{ key: 'none', d: sector(Math.PI, 0), colour: track }]
    : slices.filter((x) => x.value > 0).map((x) => {
      const a0 = angle;
      angle -= (x.value / total) * Math.PI;
      return { key: x.key, d: sector(a0, angle), colour: x.colour };
    });

  return (
    <View style={s.donutRow}>
      <View style={{ width: W, alignItems: 'center' }}>
        <Svg width={W} height={R_OUT + 2} viewBox={`0 0 ${W} ${R_OUT + 2}`}>
          {arcs.map((a) => <Path key={a.key} d={a.d} fill={a.colour} />)}
        </Svg>
        <Text style={s.donutTotal}>{total.toLocaleString('en-NZ')} {unit}</Text>
      </View>
      <View style={s.legend}>
        {slices.map((x) => (
          <View key={x.key} style={s.legendRow}>
            <View style={[s.swatch, { backgroundColor: x.colour }]} />
            <Text style={s.legendLabel}>{x.label}</Text>
            <Text style={s.legendValue}>{x.value.toLocaleString('en-NZ')}</Text>
            <Text style={s.legendShare}>{total ? `${Math.round((x.value / total) * 100)}%` : '–'}</Text>
          </View>
        ))}
      </View>
    </View>
  );
}

/* ---------- tables ---------- */

/** @param left how many leading columns are text, aligned left; the rest are figures */
function Row({ s, cells, widths, total, head, left = 1 }) {
  return (
    <View style={[s.row, head && s.headRow, total && s.totalRow]} wrap={false}>
      {cells.map((c, i) => (
        <Text key={i} style={[
          s.cell, { width: widths[i], textAlign: i < left ? 'left' : 'right' },
          head && s.headCell, total && s.totalCell,
        ]}>
          {c}
        </Text>
      ))}
    </View>
  );
}

function PropertyTable({ s, data, country, windowShort, n }) {
  const widths = ['19%', '9%', '9%', '9%', '9%', '9%', '10%', '13%', '13%'];
  const price = (v) => (v == null ? '—' : formatMoney(v, country));
  const cells = (r, label) => [
    label, n(r.created), percent(r.createdPercent), n(r.verified), n(r.closed),
    n(r.verifiedAllTime), n(r.unverifiedAllTime), price(r.averageSalePrice), price(r.maxSalePrice),
  ];
  return (
    <View style={s.table}>
      <View style={s.bandRow} wrap={false}>
        <View style={{ width: '19%' }} />
        <Text style={[s.band, { width: '36%' }]}>{windowShort}</Text>
        <Text style={[s.band, { width: '19%' }]}>All time</Text>
        <Text style={[s.band, { width: '26%' }]}>Sale prices, closed in window</Text>
      </View>
      <Row s={s} head widths={widths} cells={['Property type', 'Created', 'Share', 'Verified', 'Closed',
        'Verified', 'Unverified', 'Average', 'Highest']} />
      {data.rows.map((r) => <Row key={r.propertyType} s={s} widths={widths} cells={cells(r, propertyTypeLabel(r.propertyType))} />)}
      <Row s={s} total widths={widths} cells={cells(data.total, 'Total')} />
    </View>
  );
}

function OwnerTable({ s, data, n }) {
  const widths = ['32%', '17%', '17%', '17%', '17%'];
  const rows = data.rows.filter((r) => r.owners > 0);
  if (rows.length === 0) return <Text style={s.empty}>No owners have been recorded on deals created in this window yet.</Text>;
  return (
    <View style={s.table}>
      <Row s={s} head widths={widths} cells={['Owner type', 'Owners', 'Overseas residents', 'Re-used', 'Exceptions granted']} />
      {rows.map((r) => (
        <Row key={r.ownerType} s={s} widths={widths}
             cells={[ownerTypeLabel(r.ownerType), n(r.owners), n(r.overseas), n(r.reused), n(r.exceptions)]} />
      ))}
      <Row s={s} total widths={widths}
           cells={['Total', n(data.total.owners), n(data.total.overseas), n(data.total.reused), n(data.total.exceptions)]} />
      <Text style={s.note}>
        Every owner on both sides of a deal is counted, companies and trusts included. Re-used counts owners who also
        appear on another of the firm's deals, where they were added with the owner picker.
      </Text>
    </View>
  );
}

function TrainingTable({ s, data, n }) {
  const { summary, people } = data;
  if (people.length === 0) return <Text style={s.empty}>No training has been assigned here yet.</Text>;
  const widths = ['20%', '17%', '14%', '11%', '8%', '11%', '7%', '12%'];
  return (
    <View style={s.table}>
      <Text style={s.trainingSummary}>
        {n(summary.people)} people with training. {n(summary.coursesPassed)} of {n(summary.coursesAssigned)} courses
        passed, {n(summary.coursesOverdue)} overdue. {hours(summary.minutesAttended)} training hours in the window.
      </Text>
      <Row s={s} head left={3} widths={widths}
           cells={['Name', 'Role', 'Branch', 'Courses passed', 'Overdue', 'Sessions', 'Hours', 'Last completed']} />
      {people.map((p) => (
        <Row key={p.userId} s={s} left={3} widths={widths} cells={[
          p.fullName, roleLabel(p.role), p.branchName ?? 'Firm-level',
          p.coursesAssigned ? `${n(p.coursesPassed)} of ${n(p.coursesAssigned)}` : '—',
          n(p.coursesOverdue),
          p.sessionsAssigned ? `${n(p.sessionsAttended)} of ${n(p.sessionsAssigned)}` : '—',
          hours(p.minutesAttended),
          p.lastCompletedAt ? formatDate(p.lastCompletedAt) : '—',
        ]} />
      ))}
    </View>
  );
}

